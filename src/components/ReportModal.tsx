import React, { useState } from 'react';
import { ThreatAnalysis } from '../types/threat';
import { X, Copy, Check, Download, ShieldAlert, FileText } from 'lucide-react';

interface ReportModalProps {
  analysis: ThreatAnalysis;
  onClose: () => void;
}

export const ReportModal: React.FC<ReportModalProps> = ({ analysis, onClose }) => {
  const [copied, setCopied] = useState(false);

  const formattedReport = `=====================================================
LINKSHIELD AI — CYBERSECURITY INCIDENT THREAT REPORT
=====================================================
Incident ID: ${analysis.id}
Generated At: ${new Date(analysis.timestamp).toUTCString()}
Scanner Engine: LinkShield AI v2.4 (Gemini 3.8 Flash Hybrid)

1. TARGET IDENTIFICATION
-----------------------------------------------------
Target URL: ${analysis.url}
Registered Domain: ${analysis.deconstruction.registeredDomain}
Subdomains: ${analysis.deconstruction.subdomain || 'None'}
Top-Level Domain (TLD): .${analysis.deconstruction.tld}
Host Format: ${analysis.deconstruction.isIpAddress ? 'Raw Numeric IP Host' : 'Standard FQDN'}
Punycode / Homoglyph Present: ${analysis.deconstruction.hasPunycode ? 'YES' : 'NO'}
Shannon Entropy: ${analysis.deconstruction.entropy}

2. RISK & THREAT CLASSIFICATION
-----------------------------------------------------
Overall Threat Score: ${analysis.riskScore} / 100
Risk Level: ${analysis.riskLevel.toUpperCase()}
Decisive Verdict: ${analysis.verdict}
Attack Vector: ${analysis.attackType}
Target Impersonated Brand: ${analysis.targetBrand || 'None Identified'}

3. EXECUTIVE SUMMARY
-----------------------------------------------------
${analysis.summary}

4. PLAIN ENGLISH EXPLANATION
-----------------------------------------------------
${analysis.plainEnglishExplanation}

5. DETECTED THREAT INDICATORS (${analysis.indicators.length} TOTAL)
-----------------------------------------------------
${analysis.indicators
  .map(
    (ind, idx) =>
      `[${idx + 1}] [${ind.severity.toUpperCase()}] ${ind.name} (${ind.category})\n    ${ind.description}`
  )
  .join('\n\n')}

6. IMMEDIATE DEFENSIVE ACTION STEPS
-----------------------------------------------------
${analysis.recommendations.map((rec, idx) => `${idx + 1}. ${rec}`).join('\n')}

=====================================================
Report generated by LinkShield AI Threat Intelligence.
Submit this report to your organization's IT / SOC desk.
=====================================================`;

  const handleCopy = () => {
    navigator.clipboard.writeText(formattedReport);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const element = document.createElement('a');
    const file = new Blob([formattedReport], { type: 'text/plain' });
    element.href = URL.createObjectURL(file);
    element.download = `LinkShield-Incident-${analysis.id}.txt`;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/85 backdrop-blur-md animate-fadeIn">
      <div className="bg-[#091124] border border-cyan-500/30 rounded-2xl w-full max-w-2xl max-h-[90vh] flex flex-col shadow-2xl shadow-cyan-950/50 overflow-hidden">
        {/* Modal Header */}
        <div className="flex items-center justify-between px-6 py-4.5 border-b border-cyan-950/80 bg-[#060b17]">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-cyan-500/10 border border-cyan-500/30 flex items-center justify-center text-cyan-400">
              <FileText className="w-4 h-4" />
            </div>
            <h3 className="font-extrabold text-white text-base">
              SOC Security Incident Threat Report
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-slate-100 hover:bg-slate-800 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Content */}
        <div className="p-6 overflow-y-auto space-y-4">
          <div className="flex items-center justify-between text-xs font-mono-code text-slate-400">
            <span>Incident Reference: <strong className="text-cyan-300">{analysis.id}</strong></span>
            <span
              className={`font-bold px-2.5 py-0.5 rounded-md border uppercase ${
                analysis.riskLevel === 'dangerous'
                  ? 'bg-rose-950 text-rose-300 border-rose-800'
                  : analysis.riskLevel === 'suspicious'
                  ? 'bg-amber-950 text-amber-300 border-amber-800'
                  : 'bg-emerald-950 text-emerald-300 border-emerald-800'
              }`}
            >
              {analysis.riskScore}/100 {analysis.riskLevel}
            </span>
          </div>

          <pre className="p-4 bg-[#060b17] rounded-xl border border-cyan-950/60 font-mono-code text-[11px] text-slate-300 whitespace-pre-wrap leading-relaxed select-all">
            {formattedReport}
          </pre>
        </div>

        {/* Modal Footer */}
        <div className="flex items-center justify-end gap-3 px-6 py-4 border-t border-cyan-950/80 bg-[#060b17]">
          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-4 py-2 text-xs font-semibold rounded-xl bg-slate-800/80 hover:bg-slate-700 text-slate-200 border border-slate-700 transition-colors cursor-pointer"
          >
            <Download className="w-4 h-4 text-cyan-400" />
            <span>Download .txt</span>
          </button>

          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-5 py-2 text-xs font-extrabold rounded-xl bg-gradient-to-r from-blue-600 via-cyan-500 to-teal-400 hover:brightness-110 text-slate-950 transition-all cursor-pointer shadow-md shadow-cyan-500/25"
          >
            {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
            <span>{copied ? 'Report Copied' : 'Copy Incident Text'}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
